import { configs, from, to } from 'opencc-js/preset';
import { mkdirSync, writeFileSync, copyFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

// Preserve the pinned opencc-js dictionary order and segmentation contracts.
const dictionaries = [];
const id = value => {
  let index = dictionaries.indexOf(value);
  if (index < 0) { index = dictionaries.length; dictionaries.push(value); }
  return index;
};
const groups = value => Array.isArray(value[0]) ? value : [value];
const pairs = [['cn', 'tw'], ['cn', 'hk'], ['cn', 't'], ['tw', 'cn'], ['hk', 'cn'], ['t', 'cn'], ['tw', 'hk'], ['hk', 'tw']];
const converters = pairs.map(([source, target]) => {
  const name = source === 'cn' ? `s2${target}` : target === 'cn' ? `${source}2s` : `${source}2${target}`;
  const config = configs[name];
  return config
    ? { segmentation: id(config.segmentation), chain: config.conversionChain.map(group => group.map(id)) }
    : { segmentation: null, chain: [...(source === 't' ? [] : groups(from[source])), ...(target === 't' ? [] : groups(to[target]))].map(group => group.map(id)) };
});
const directory = new URL('../core/Echo.Core/Search/Data/', import.meta.url);
mkdirSync(directory, { recursive: true });
writeFileSync(new URL('opencc-search.json.gz', directory), gzipSync(JSON.stringify({ dictionaries, converters }), { level: 9 }));
copyFileSync(new URL('../node_modules/opencc-js/LICENSE', import.meta.url), new URL('OPENCC-LICENSE.txt', directory));
copyFileSync(new URL('../node_modules/opencc-js/THIRD_PARTY_LICENSES.md', import.meta.url), new URL('OPENCC-THIRD-PARTY.md', directory));
const ranges = [];
let start = null;
const cjk = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}]/u;
for (let code = 0; code <= 0x110000; code++) {
  const match = code < 0x110000 && cjk.test(String.fromCodePoint(code));
  if (match && start === null) start = code;
  if (!match && start !== null) { ranges.push([start, code - 1]); start = null; }
}
writeFileSync(new URL('../SearchUnicodeRanges.cs', directory), `// Generated by scripts/generate-core-search-data.mjs; Node Unicode ${process.versions.unicode}.\nnamespace Echo.Core.Search;\n\ninternal static class SearchUnicodeRanges\n{\n    public static bool IsCjk(int value) => value is\n${ranges.map(([lo, hi]) => `        >= 0x${lo.toString(16)} and <= 0x${hi.toString(16)}`).join(' or\n')};\n}\n`);
